def main():
    parser = argparse.ArgumentParser(description="Whisper decode (batched) + WER/Disfl/Halluc metrics.")
    parser.add_argument("--wav_scp", required=True, type=str)
    parser.add_argument("--trn_scp", required=True, type=str)
    parser.add_argument("--model", required=True, type=str)
    parser.add_argument("--processor", required=True, type=str)
    parser.add_argument("--result_ref_file", required=True, type=str)
    parser.add_argument("--result_hyp_file", required=True, type=str)
    parser.add_argument("--compute_wer", default=True, type=str2bool)
    parser.add_argument("--chunk_length", default=30, type=int)
    parser.add_argument("--batch_size", default=8, type=int)
    parser.add_argument("--num_workers", default=0, type=int)
    parser.add_argument("--device", default="auto", type=str)
    parser.add_argument("--dtype", default="auto", choices=["auto", "float16", "float32"])
    parser.add_argument("--disfl_window", default=2, type=int)
    parser.add_argument("--disfl_include_repair_markers", action="store_true")
    parser.add_argument("--disfl_enforce_token_match", action="store_true")
    parser.add_argument("--attn_implementation", default=None, choices=["eager", "sdpa"],
                        help="Default: sdpa for zero-shot models and BitFit/RED/LoReFT, eager otherwise. "
                             "LoRA and JoLA/AURA require eager.")
    parser.add_argument("--sink_gate_disable_features", nargs="*", default=[],
                        choices=["max_prob", "norm_entropy", "shift"],
                        help="SinkGate features zeroed at inference (AURA feature ablation).")
    args = parser.parse_args()

    if transformers.__version__ != "4.48.3":
        warnings.warn(f"This code was tested with transformers==4.48.3, found {transformers.__version__}.")
    patch_long_form_generation()

    device = resolve_device(args.device)
    torch_dtype = resolve_torch_dtype(device, args.dtype)

    data_path = {"data": {"scp_path": args.wav_scp, "text_label": args.trn_scp}}
    dataset = WhisperDataset(data_path, for_decode=True).data

    print("Loading model...", flush=True)
    print(f"  device={device}  dtype={torch_dtype}")
    model, processor = load_model_and_processor(args.model, args.processor, device, torch_dtype, args.attn_implementation)

    if args.sink_gate_disable_features:
        n_gates = set_sink_gate_disabled_features(model, args.sink_gate_disable_features)
        if n_gates == 0:
            raise ValueError("--sink_gate_disable_features requires a model with SinkGate modules (AURA).")
        print(f"  SinkGate features disabled: {args.sink_gate_disable_features} ({n_gates} modules)")

    lang_kwargs, long_lang_kwargs = language_kwargs(model, args.model)
    if lang_kwargs or long_lang_kwargs:
        print(f"  forced generation: batched={lang_kwargs}  long-form={long_lang_kwargs}")

    # Split long vs normal; sort normals by duration (longest first) to reduce padding churn.
    long_items, normal_items, utt_order = [], [], []
    for it in dataset:
        utt_order.append(it["utt_id"])
        audio = it["audio"]
        dur = len(audio["array"]) / audio["sampling_rate"]
        if dur < 0.5:
            # Not decoded: empty hypothesis.
            it["_too_short"] = True
            long_items.append(it)
        elif dur > args.chunk_length:
            it["_too_short"] = False
            long_items.append(it)
        else:
            it["_too_short"] = False
            normal_items.append(it)

    normal_items.sort(
        key=lambda it: len(it["audio"]["array"]) / it["audio"]["sampling_rate"],
        reverse=True,
    )

    print(f"Total utts : {len(dataset)}")
    print(f"  long/short (no-batch) : {len(long_items)}")
    print(f"  normal (batched)      : {len(normal_items)}")

    raw_by_utt: Dict[str, Tuple[str, str]] = {}  # utt_id → (raw_ref, raw_hyp)

    # 1) Long / too-short items — sequential.
    for idx, it in enumerate(long_items, 1):
        if it.get("_too_short"):
            raw_prediction = ""
        else:
            raw_prediction = process_long_audio(it, processor, model, device, long_lang_kwargs)
        raw_by_utt[it["utt_id"]] = (it["sentence"].strip(), raw_prediction)
        if idx % 50 == 0 or idx == len(long_items):
            print(f"  long: {idx}/{len(long_items)}", flush=True)

    # 2) Normal items — DataLoader batches.
    if normal_items:
        loader = DataLoader(
            normal_items,
            batch_size=args.batch_size,
            shuffle=False,
            num_workers=args.num_workers,
            pin_memory=device.startswith("cuda"),
            collate_fn=lambda batch: collate_batch(batch, processor),
        )
        done = 0
        for input_features, attention_mask, sentences, utt_ids in loader:
            input_features = input_features.to(device=device, dtype=model.dtype)
            gen_kwargs = {"input_features": input_features}
            if attention_mask is not None:
                gen_kwargs["attention_mask"] = attention_mask.to(device)
            gen_kwargs.update(lang_kwargs)
            with torch.inference_mode():
                generated_ids = model.generate(**gen_kwargs)
            predictions = processor.batch_decode(generated_ids, skip_special_tokens=True)
            for pred, sent, uid in zip(predictions, sentences, utt_ids):
                raw_by_utt[uid] = (sent.strip(), pred)
            done += len(utt_ids)
            if done % 200 == 0 or done == len(normal_items):
                print(f"  normal: {done}/{len(normal_items)}", flush=True)

    # ------------------------------------------------------------
    # Metrics — walk the utterances in original order.
    # ------------------------------------------------------------
    norm_refs, norm_hyps = [], []
    all_norm_hyps, all_norm_refs = [], []  # every utt, for the hallucination rates
    all_raw_hyps = []
    pre_speech_refs, pre_speech_hyps = [], []
    total_tp = total_ref = total_hyp = 0
    total_hallucinations = 0
    hallucination_examples: List[str] = []

    with open(args.result_ref_file, "w", encoding="utf-8") as ref_w, \
         open(args.result_hyp_file, "w", encoding="utf-8") as hyp_w:
        for uid in utt_order:
            raw_ref, raw_hyp = raw_by_utt[uid]

            is_h, trig = detect_hallucination_and_looping(raw_hyp)
            if is_h:
                total_hallucinations += 1
                if len(hallucination_examples) < 5:
                    hallucination_examples.append(f"HYP: {raw_hyp[:50]}... [Trig: {trig}]")

            if raw_ref and raw_ref != "<UNK>":
                pre_speech_refs.append(speech_clean(raw_ref))
                pre_speech_hyps.append(speech_clean(raw_hyp))
                ref_ev = extract_disfluency_events(raw_ref, args.disfl_include_repair_markers, 1)
                hyp_ev = extract_disfluency_events(raw_hyp, args.disfl_include_repair_markers, 1)
                tp, rt, ht = match_events_window(ref_ev, hyp_ev, args.disfl_window, args.disfl_enforce_token_match)
                total_tp += tp; total_ref += rt; total_hyp += ht

            # A literal <UNK> reference is scored as one word; an empty hypothesis is written as <UNK>.
            norm_ref = "<UNK>" if raw_ref == "<UNK>" else processor.tokenizer._normalize(raw_ref)
            norm_hyp = "<UNK>" if not raw_hyp.strip() else processor.tokenizer._normalize(raw_hyp)
            all_norm_refs.append(norm_ref)
            all_norm_hyps.append(norm_hyp)
            all_raw_hyps.append(raw_hyp)
            if args.compute_wer and len(norm_ref) > 0:
                norm_refs.append(norm_ref)
                norm_hyps.append(norm_hyp)

            uid_fmt = uid.replace("-", "_")
            ref_w.write(norm_ref.upper() + " (" + uid_fmt + ")\n")
            hyp_w.write(norm_hyp.upper() + " (" + uid_fmt + ")\n")

    # 1. Standard WER + breakdown
    if args.compute_wer and norm_refs:
        wer_out = jiwer.process_words(norm_refs, norm_hyps)
        N = wer_out.hits + wer_out.substitutions + wer_out.deletions
        print("\n" + "=" * 70)
        print("STANDARD WER (Post-Norm) & BREAKDOWN")
        print("=" * 70)
        print(f"Total WER:     {wer_out.wer * 100:.2f} %")
        print("-" * 30)
        if N > 0:
            print(f"Substitution:  {wer_out.substitutions / N * 100:.2f} %")
            print(f"Deletion:      {wer_out.deletions / N * 100:.2f} %")
            print(f"Insertion:     {wer_out.insertions / N * 100:.2f} %")
        print("=" * 70, flush=True)

    # 2. Speech WER
    if pre_speech_refs:
        speech_res = jiwer.process_words(pre_speech_refs, pre_speech_hyps)
        print(f"SPEECH WER (Pre-Norm): {speech_res.wer * 100:.2f} %")
        print("-" * 70, flush=True)

    # 3. Disfluency F1
    prec = total_tp / total_hyp if total_hyp > 0 else 0.0
    rec = total_tp / total_ref if total_ref > 0 else 0.0
    f1 = (2 * prec * rec / (prec + rec)) if (prec + rec) > 0 else 0.0
    print("DISFLUENCY F1")
    print(f"Precision: {prec * 100:.2f}% | Recall: {rec * 100:.2f}% | F1: {f1 * 100:.2f}")
    print("-" * 70, flush=True)

    # 4. Hallucinations
    n = len(dataset)
    hr = (total_hallucinations / n) * 100 if n > 0 else 0.0
    print("HALLUCINATION METRICS")
    print(f"Detected: {total_hallucinations} / {n} utts ({hr:.2f}%)")
    if hallucination_examples:
        print("Examples:", hallucination_examples[0])
    print("-" * 70, flush=True)

    # 5. HR_norm: % utts whose normalized hypothesis is non-empty and not <UNK>.
    n_nonempty_hyp = sum(1 for h in all_norm_hyps if h and h != "<UNK>" and h.strip())
    n_empty_ref = sum(1 for r in all_norm_refs if not r or not r.strip())
    hr_calm = (n_nonempty_hyp / n) * 100 if n > 0 else 0.0
    print(f"Hallucination Rate (CALM-style, non-empty-hyp): {hr_calm:.2f} %  "
          f"({n_nonempty_hyp}/{n} non-empty;  {n_empty_ref} refs were empty)")

    # 6. HR_raw: % utts whose raw hypothesis is non-empty after .strip().
    n_raw_strip_nonempty = sum(1 for r in all_raw_hyps if r and r.strip())
    hr_strip = (n_raw_strip_nonempty / n) * 100 if n > 0 else 0.0
    print(f"Hallucination Rate (raw .strip() != ''): {hr_strip:.2f} %  "
          f"({n_raw_strip_nonempty}/{n} non-empty raw)")
    print("=" * 70, flush=True)


