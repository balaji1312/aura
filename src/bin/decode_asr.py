#!/usr/bin/env python3
"""Whisper decoding with batched inference + full metric suite.

Handles zero-shot models, full fine-tuning and every PEFT method (LoRA, JoLA,
AURA, AURA+Enc, BitFit, RED, LoReFT). Utterances shorter than 0.5 s are not
decoded. Long audio (> chunk_length s) is decoded one at a time with Whisper's
long-form generation; the rest is sorted by duration and batched. Output file
order matches the input `wav_scp` order.

Metrics:
  1. Standard post-norm WER + Ins/Del/Sub breakdown
  2. Speech WER (pre-normalization, hesitation/number folding)
  3. Disfluency F1 (event-based)
  4. Hallucination detection (trigger phrases + 4-gram looping)
  5. Hallucination rates: non-empty normalized hypothesis, non-empty raw hypothesis
"""

