def str2bool(value):
    if isinstance(value, bool):
        return value
    v = value.lower()
    if v in {"true", "1", "yes", "y"}:
        return True
    if v in {"false", "0", "no", "n"}:
        return False
    raise argparse.ArgumentTypeError(f"Invalid boolean: {value}")


def resolve_device(name: str) -> str:
    if name == "auto":
        return "cuda" if torch.cuda.is_available() else "cpu"
    if name.startswith("cuda") and not torch.cuda.is_available():
        raise ValueError("CUDA requested but unavailable.")
    return name


def resolve_torch_dtype(device: str, name: str) -> torch.dtype:
    if name == "auto":
        return torch.float16 if device.startswith("cuda") else torch.float32
    m = {"float16": torch.float16, "float32": torch.float32}
    dt = m[name]
    if device == "cpu" and dt == torch.float16:
        raise ValueError("float16 requires CUDA.")
    return dt


def move_batch_to_device(batch, device: str, dtype: torch.dtype):
    out = {}
    for k, v in batch.items():
        if torch.is_tensor(v):
            out[k] = v.to(device=device, dtype=dtype) if v.is_floating_point() else v.to(device=device)
        else:
            out[k] = v
    return out


def collate_batch(batch: List[dict], processor: WhisperProcessor):
    arrays = [it["audio"]["array"] for it in batch]
    srs = [it["audio"]["sampling_rate"] for it in batch]
    if len(set(srs)) != 1:
        raise ValueError(f"Mixed sampling rates: {sorted(set(srs))}")
    inputs = processor(
        arrays,
        return_tensors="pt",
        padding="max_length",
        return_attention_mask=True,
        sampling_rate=srs[0],
    )
    attn = getattr(inputs, "attention_mask", None)
    return (
        inputs.input_features,
        attn,
        [it["sentence"] for it in batch],
        [it["utt_id"] for it in batch],
    )


def process_long_audio(item: dict, processor: WhisperProcessor, model, device: str, gen_kwargs: dict) -> str:
    audio = item["audio"]
    inputs = processor(
        audio["array"],
        return_tensors="pt",
        truncation=False,
        padding="longest",
        return_attention_mask=True,
        sampling_rate=audio["sampling_rate"],
    )
    inputs = move_batch_to_device(inputs, device, model.dtype)
    with torch.inference_mode():
        segments = model.generate(**inputs, return_timestamps=True, **gen_kwargs)[0]
    return processor.decode(segments, skip_special_tokens=True)


def patch_long_form_generation():
    """Guard `generate_with_fallback` (transformers 4.48.3) against empty segment outputs.

    A model that stops immediately (e.g. on non-speech) yields an empty `seek_sequence`,
    which the padding/EOS trimming indexes with `seek_sequence[-1]`.
    """
    mixin = generation_whisper.WhisperGenerationMixin
    if transformers.__version__ != "4.48.3" or getattr(mixin.generate_with_fallback, "empty_segment_guard", False):
        return
    src = textwrap.dedent(inspect.getsource(mixin.generate_with_fallback))
    if "len(seek_sequence)" in src:
        return
    for token_id in ("pad_token_id", "eos_token_id"):
        old = f" if seek_sequence[-1] == generation_config.{token_id}:"
        new = f" if len(seek_sequence) > 0 and seek_sequence[-1] == generation_config.{token_id}:"
        if src.count(old) != 1:
            raise RuntimeError("Unexpected transformers generate_with_fallback source; cannot apply the long-form guard.")
        src = src.replace(old, new)
    # The enclosing `__class__` keeps the zero-argument super() of the method bound to the mixin.
    code = "def _build(__class__):\n" + textwrap.indent(src, "    ") + "    return generate_with_fallback\n"
    scope = {}
    exec(code, vars(generation_whisper), scope)
    patched = scope["_build"](mixin)
    patched.empty_segment_guard = True
    mixin.generate_with_fallback = patched


def is_zero_shot(config, model_path: str) -> bool:
    """A pretrained Hub model: no peft_config, no label_prefix, not a local checkpoint."""
    return (
        getattr(config, "peft_config", None) is None
        and getattr(config, "label_prefix", None) is None
        and not os.path.isdir(model_path)
    )


def language_kwargs(model, model_path: str) -> Tuple[dict, dict]:
    """Language/task forced at generation, for the batched and the long-form path.

    Multilingual checkpoints trained with the full label prefix (config.label_prefix == 'full')
    decode with the language and task of that prefix. Multilingual zero-shot models are forced
    to English transcription on the batched path only. Checkpoints without label_prefix are not forced.
    """
    if not getattr(model.generation_config, "is_multilingual", False):
        return {}, {}
    if getattr(model.config, "label_prefix", None) == "full":
        trained = {"language": model.config.label_language, "task": model.config.label_task}
        return trained, trained
    if is_zero_shot(model.config, model_path):
        return {"language": "en", "task": "transcribe"}, {}
    return {}, {}


def _load_state_dict_from_dir(model_dir: str) -> dict:
    """Load a (possibly-sharded) state dict from a HF-style checkpoint dir."""
    sf_files = sorted(glob.glob(os.path.join(model_dir, "model*.safetensors")))
    bin_files = sorted(glob.glob(os.path.join(model_dir, "pytorch_model*.bin")))
    state: dict = {}
    if sf_files:
        from safetensors.torch import load_file as load_safetensors
        for f in sf_files:
            state.update(load_safetensors(f))
    elif bin_files:
        for f in bin_files:
            state.update(torch.load(f, map_location="cpu"))
    else:
        raise FileNotFoundError(f"No safetensors or pytorch_model.bin found in {model_dir}")
    return state


def load_model_and_processor(model_path: str, processor_path: str, device: str, torch_dtype: torch.dtype,
                             attn_implementation: Optional[str] = None):
    config = AutoConfig.from_pretrained(model_path)
    feature_extractor = WhisperFeatureExtractor.from_pretrained(processor_path)
    processor = WhisperProcessor.from_pretrained(processor_path)
    processor.current_processor = feature_extractor
    processor.feature_extractor = feature_extractor

    peft_config = PEFTArguments.from_saved(getattr(config, "peft_config", None))
    peft_type = peft_config.peft_type if peft_config is not None else None

    if attn_implementation is None:
        attn_implementation = "sdpa" if peft_type in INTERVENTIONS or is_zero_shot(config, model_path) else "eager"
    if peft_type in ("jola", "lora") and attn_implementation != "eager":
        raise ValueError(f"peft_type '{peft_type}' requires attn_implementation 'eager'.")
    print(f"  peft_type={peft_type}  attn_implementation={attn_implementation}")

    if peft_config is not None:
        config.peft_config = peft_config

    if peft_type in INTERVENTIONS:
        # Empty model + re-installed intervention, then the checkpoint weights on top.
        config._attn_implementation = attn_implementation
        model = WhisperForConditionalGeneration(config)
        intervention = install_intervention(model, peft_config)

        state = _load_state_dict_from_dir(model_path)
        missing, unexpected = model.load_state_dict(state, strict=False)
        if unexpected:
            print(f"[warn] ckpt has unexpected keys (first 5): {unexpected[:5]}")
        # proj_out.weight is tied to the decoder token embedding and not saved.
        missing = [k for k in missing if k != "proj_out.weight"]
        if missing:
            raise RuntimeError(f"ckpt is missing keys (first 5): {missing[:5]}")

        # The empty model has a bare GenerationConfig; long-form generation needs
        # the saved one (no_timestamps_token_id, alignment heads, language ids).
        for _gc_dir in (model_path, processor_path):
            try:
                model.generation_config = GenerationConfig.from_pretrained(_gc_dir)
                break
            except (OSError, EnvironmentError):
                continue

        model = model.to(device=device, dtype=torch_dtype)
        intervention.post_dtype_cast(model)
    else:
        model = WhisperForConditionalGeneration.from_pretrained(
            model_path,
            config=config,
            low_cpu_mem_usage=True,
            torch_dtype=torch_dtype,
            attn_implementation=attn_implementation,
        ).to(device)
    model.eval()
    model.config.forced_decoder_ids = None
    model.generation_config.forced_decoder_ids = None

    return model, processor


