# ------------------------------------------------------------------
# 1. Hallucination detection
# ------------------------------------------------------------------

HALLUCINATION_TRIGGERS = {
    "subtitles by", "subtitle by", "captioning", "copyright",
    "thank you for watching", "thanks for watching", "subscribe",
    "like and subscribe", "provided by", "generated by",
    "community contributions", "closed captioning",
    "alara", "amara", "mbc",
    "audiobook", "chapter",
    "www.", ".com", "http", "https", "youtube",
}


def detect_hallucination_and_looping(text: str) -> Tuple[bool, Optional[str]]:
    text_lower = text.lower().strip()
    if not text_lower:
        return False, None
    for trigger in HALLUCINATION_TRIGGERS:
        if trigger in text_lower:
            return True, f"Trigger: {trigger}"
    words = text_lower.split()
    if len(words) > 10:
        if words[-4:] == words[-8:-4]:
            return True, "Looping: 4-gram"
    return False, None


# ------------------------------------------------------------------
# 2. Speech-WER normalization
# ------------------------------------------------------------------

HESITATIONS = {"uh", "umm", "um", "er", "erm", "ah", "eh", "huh", "hm", "hmm", "mm", "mmm", "em"}

NUM_WORDS = {
    **{w: str(i) for i, w in enumerate(
        ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"])},
    **{w: str(i) for w, i in
       [("ten", 10), ("eleven", 11), ("twelve", 12), ("thirteen", 13),
        ("fourteen", 14), ("fifteen", 15), ("sixteen", 16),
        ("seventeen", 17), ("eighteen", 18), ("nineteen", 19)]},
    **{w: str(10 * i) for i, w in
       enumerate(["", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety"])},
}


def _standardise_numbers(tokens: List[str]) -> List[str]:
    out: List[str] = []
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if (i + 1 < len(tokens)
            and tok in NUM_WORDS
            and tokens[i + 1] in NUM_WORDS
            and int(NUM_WORDS[tok]) % 10 == 0
            and int(NUM_WORDS[tok]) >= 20):
            out.append(str(int(NUM_WORDS[tok]) + int(NUM_WORDS[tokens[i + 1]])))
            i += 2
            continue
        out.append(NUM_WORDS[tok] if tok in NUM_WORDS else tok)
        i += 1
    return out


def speech_clean(text: str) -> str:
    text = text.lower().encode("ascii", "ignore").decode("ascii")
    text = re.sub(r"[^\w\s%\-\d]", "", text)
    tokens = re.sub(r"-", " ", text).split()
    tokens = ["%hes%" if tok in HESITATIONS else tok for tok in tokens]
    tokens = _standardise_numbers(tokens)
    collapsed: List[str] = []
    for tok, grp in groupby(tokens):
        run_len = sum(1 for _ in grp)
        collapsed.extend([tok] if run_len >= 4 else [tok] * run_len)
    return " ".join(collapsed)


# ------------------------------------------------------------------
# 3. Disfluency F1
# ------------------------------------------------------------------

@dataclass(frozen=True)
class DisflEvent:
    typ: str
    token: str
    pos: int


FILLED_PAUSES_TEXT = {"um", "uh", "er", "ah", "mm", "hmm", "huh", "em"}
REPAIR_MARKERS = {("i", "mean"), ("you", "know")}


def _basic_tokenize_for_disfluency(text: str) -> List[str]:
    text = text.lower().encode("ascii", "ignore").decode("ascii")
    text = re.sub(r"[^\w\s\-]", "", text)
    return text.split()


def extract_disfluency_events(text: str, include_repair_markers: bool = False, rep_window: int = 1) -> List[DisflEvent]:
    toks = _basic_tokenize_for_disfluency(text)
    events: List[DisflEvent] = []
    for i, t in enumerate(toks):
        if t in FILLED_PAUSES_TEXT:
            events.append(DisflEvent("FP", t, i))
        if t == "-" or t.endswith("-"):
            events.append(DisflEvent("PW", t, i))
    if rep_window == 1:
        for i in range(1, len(toks)):
            if toks[i] == toks[i - 1] and toks[i] != "-":
                events.append(DisflEvent("REP", toks[i], i))
    if include_repair_markers and len(toks) >= 2:
        for i in range(len(toks) - 1):
            bg = (toks[i], toks[i + 1])
            if bg in REPAIR_MARKERS:
                events.append(DisflEvent("RM", " ".join(bg), i))
    return events


def match_events_window(ref_events, hyp_events, window=2, enforce_token_match=True):
    ref_total, hyp_total = len(ref_events), len(hyp_events)
    if ref_total == 0 and hyp_total == 0:
        return 0, 0, 0
    hyp_by_key = defaultdict(list)
    for j, e in enumerate(hyp_events):
        key = (e.typ, e.token) if enforce_token_match else (e.typ, "")
        hyp_by_key[key].append(j)
    used_hyp, tp = set(), 0
    for e in ref_events:
        key = (e.typ, e.token) if enforce_token_match else (e.typ, "")
        candidates = hyp_by_key.get(key, [])
        best_j, best_dist = None, None
        for j in candidates:
            if j in used_hyp:
                continue
            dist = abs(hyp_events[j].pos - e.pos)
            if dist <= window and (best_dist is None or dist < best_dist):
                best_j, best_dist = j, dist
        if best_j is not None:
            used_hyp.add(best_j)
            tp += 1
    return tp, ref_total, hyp_total


